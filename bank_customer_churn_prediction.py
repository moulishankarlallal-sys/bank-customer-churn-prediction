# Original input features
features = [
    "CreditScore",
    "Geography",
    "Gender",
    "Age",
    "Tenure",
    "Balance",
    "NumOfProducts",
    "HasCrCard",
    "IsActiveMember",
    "EstimatedSalary"
]

target = "Exited"

# Check that required columns exist
required_columns = features + [target]
missing_columns = [
    col for col in required_columns if col not in df.columns
]

if missing_columns:
    raise ValueError(
        f"Required columns are missing: {missing_columns}"
    )

# Select only the required columns
model_df = df[required_columns].copy()

# Remove rows without a known target
model_df = model_df.dropna(subset=[target])

# Ensure the target contains valid binary values
model_df[target] = pd.to_numeric(
    model_df[target], errors="coerce"
)

model_df = model_df.dropna(subset=[target])

if not model_df[target].isin([0, 1]).all():
    raise ValueError("Exited must contain only 0 and 1.")

model_df[target] = model_df[target].astype(int)

X = model_df[features]
y = model_df[target]

numeric_features = [
    "CreditScore", "Age", "Tenure", "Balance",
    "NumOfProducts", "HasCrCard", "IsActiveMember",
    "EstimatedSalary"
]

categorical_features = ["Geography", "Gender"]

print("Features and target prepared.")
print("Number of usable records:", len(model_df))
print("Number of input features:", len(features))

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training records:", len(X_train))
print("Testing records:", len(X_test))

print("\nTraining churn distribution:")
print(y_train.value_counts(normalize=True).round(3))

print("\nTesting churn distribution:")
print(y_test.value_counts(normalize=True).round(3))

numeric_pipeline = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler())
])

categorical_pipeline = Pipeline([
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("encoder", OneHotEncoder(handle_unknown="ignore"))
])

preprocessor = ColumnTransformer([
    ("numeric", numeric_pipeline, numeric_features),
    ("categorical", categorical_pipeline, categorical_features)
])

print("Preprocessing pipeline created.")

models = {
    "Logistic Regression": LogisticRegression(
        max_iter=1000,
        class_weight="balanced",
        random_state=42
    ),

    "Random Forest": RandomForestClassifier(
        n_estimators=200,
        max_depth=12,
        min_samples_leaf=3,
        class_weight="balanced",
        random_state=42,
        n_jobs=-1
    ),

    "Gradient Boosting": GradientBoostingClassifier(
        n_estimators=150,
        learning_rate=0.05,
        max_depth=3,
        random_state=42
    )
}

trained_models = {}
results = {}

for name, model in models.items():

    pipeline = Pipeline([
        ("preprocessor", preprocessor),
        ("model", model)
    ])

    print(f"Training {name}...")

    pipeline.fit(X_train, y_train)

    predictions = pipeline.predict(X_test)
    probabilities = pipeline.predict_proba(X_test)[:, 1]

    results[name] = {
        "Accuracy": accuracy_score(y_test, predictions),
        "Precision": precision_score(
            y_test, predictions, zero_division=0
        ),
        "Recall": recall_score(
            y_test, predictions, zero_division=0
        ),
        "F1 Score": f1_score(
            y_test, predictions, zero_division=0
        ),
        "ROC-AUC": roc_auc_score(y_test, probabilities)
    }

    trained_models[name] = pipeline

print("\nAll three models trained successfully!")

results_df = pd.DataFrame(results).T
results_df.index.name = "Model"

results_df = results_df.sort_values(
    by="ROC-AUC",
    ascending=False
)

display(results_df.round(4))

best_model_name = results_df.index[0]
best_model = trained_models[best_model_name]

best_predictions = best_model.predict(X_test)
best_probabilities = best_model.predict_proba(X_test)[:, 1]

print("Best model by ROC-AUC:", best_model_name)

print("\nClassification Report:")
print(classification_report(
    y_test,
    best_predictions,
    target_names=["Retained", "Churned"],
    zero_division=0
))

print("\nConfusion Matrix:")
cm = confusion_matrix(y_test, best_predictions)
print(cm)

plt.figure(figsize=(6, 4))
plt.imshow(cm, interpolation="nearest")
plt.title(f"Confusion Matrix — {best_model_name}")
plt.xlabel("Predicted Class")
