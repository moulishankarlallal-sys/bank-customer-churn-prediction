import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import joblib

from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (
    accuracy_score, precision_score, recall_score,
    f1_score, roc_auc_score, classification_report,
    ConfusionMatrixDisplay
)

print("Libraries imported successfully!")

df = pd.read_csv("/content/European Bank.csv")

print("Dataset shape:", df.shape)
display(df.head())

print("Column names:")
print(df.columns.tolist())

print("\nDataset information:")
df.info()

print("\nStatistical summary:")
display(df.describe(include="all").T)

print("Missing values:")
print(df.isnull().sum())

print("Duplicate rows:", df.duplicated().sum())

features = [
    "CreditScore", "Geography", "Gender", "Age",
    "Tenure", "Balance", "NumOfProducts",
    "HasCrCard", "IsActiveMember", "EstimatedSalary"
]

target = "Exited"

missing = [c for c in features + [target] if c not in df.columns]
if missing:
    raise ValueError(f"Missing columns: {missing}")

df = df.dropna(subset=[target]).copy()
df[target] = pd.to_numeric(df[target], errors="coerce")
df = df[df[target].isin([0, 1])].copy()
df[target] = df[target].astype(int)

X = df[features].copy()
y = df[target].copy()

print("Features and target prepared.")

churn_counts = y.value_counts().sort_index()

print("Retained customers (0):", churn_counts.get(0, 0))
print("Churned customers (1):", churn_counts.get(1, 0))
print(f"Churn rate: {y.mean() * 100:.2f}%")

churn_counts.rename(index={0: "Retained", 1: "Churned"}).plot(
    kind="bar", title="Customer Churn Distribution"
)
plt.xlabel("Customer Status")
plt.ylabel("Number of Customers")
plt.xticks(rotation=0)
plt.show()

numeric_features = [
    "CreditScore", "Age", "Tenure", "Balance",
    "NumOfProducts", "HasCrCard", "IsActiveMember",
    "EstimatedSalary"
]

categorical_features = ["Geography", "Gender"]

print("Numeric features:", numeric_features)
print("Categorical features:", categorical_features)

numeric_pipeline = Pipeline([
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler())
])

categorical_pipeline = Pipeline([
    ("imputer", SimpleImputer(strategy="most_frequent")),
    ("onehot", OneHotEncoder(handle_unknown="ignore"))
])

preprocessor = ColumnTransformer([
    ("numeric", numeric_pipeline, numeric_features),
    ("categorical", categorical_pipeline, categorical_features)
])

print("Preprocessing pipeline created.")

X_train, X_test, y_train, y_test = train_test_split(
    X, y,
    test_size=0.20,
    random_state=42,
    stratify=y
)

print("Training records:", len(X_train))
print("Testing records:", len(X_test))

model = Pipeline([
    ("preprocessor", preprocessor),
    ("classifier", RandomForestClassifier(
        n_estimators=300,
        min_samples_leaf=2,
        class_weight="balanced",
        random_state=42,
        n_jobs=-1
    ))
])

print("Random Forest model created.")

model.fit(X_train, y_train)

print("Model training completed successfully!")

y_pred = model.predict(X_test)
y_probability = model.predict_proba(X_test)[:, 1]

print("First 10 predicted classes:", y_pred[:10])
print("First 10 churn probabilities:", y_probability[:10])

print("Accuracy:", round(accuracy_score(y_test, y_pred), 3))
print("Precision:", round(
    precision_score(y_test, y_pred, zero_division=0), 3
))
print("Recall:", round(
    recall_score(y_test, y_pred, zero_division=0), 3
))
print("F1-score:", round(
    f1_score(y_test, y_pred, zero_division=0), 3
))
print("ROC-AUC:", round(roc_auc_score(y_test, y_probability), 3))

print("\nClassification Report:")
print(classification_report(y_test, y_pred, zero_division=0))

ConfusionMatrixDisplay.from_predictions(y_test, y_pred)

plt.title("Bank Customer Churn - Confusion Matrix")
plt.tight_layout()
plt.show()

results = df.copy()

results["Predicted_Churn_Probability"] = model.predict_proba(X)[:, 1]
results["Predicted_Risk_Percent"] = (
    results["Predicted_Churn_Probability"] * 100
).round(2)

results["Predicted_Risk_Category"] = pd.cut(
    results["Predicted_Churn_Probability"],
    bins=[-0.001, 0.30, 0.60, 1.0],
    labels=["Low", "Medium", "High"],
    include_lowest=True
)

display(
    results.sort_values(
        "Predicted_Risk_Percent", ascending=False
    )[
        [c for c in [
            "CustomerId", "Geography", "Age", "Exited",
            "Predicted_Risk_Percent", "Predicted_Risk_Category"
        ] if c in results.columns]
    ].head(10)
)

results.to_csv(
    "/content/bank_customer_churn_predictions.csv",
    index=False
)

ConfusionMatrixDisplay.from_predictions(y_test, y_pred)
plt.title("Bank Customer Churn - Confusion Matrix")
plt.tight_layout()
plt.savefig("/content/churn_confusion_matrix.png", dpi=150)
plt.show()

joblib.dump(model, "/content/bank_customer_churn_model.joblib")

print("All project outputs saved successfully!")

